// W9 media bytes — the object-store port and its local-disk adapter.
//
// PostgreSQL keeps what a media item IS (type, size, hash, room, uploader, removal). The bytes
// live behind this port. The port is deliberately tiny - put, get, delete by an opaque key - so
// an S3-compatible or Firebase Storage adapter can replace the disk adapter without touching a
// route or a rule. Until such an adapter is approved and configured, the disk adapter is the only
// one, and it is used only when FAMILY_CHAT_MEDIA_DIR is set. With no directory configured, every
// media route answers `chat_media_unavailable`: there is no silent fallback to some default path.
//
// Keys are generated by the server (a random UUID) and validated before use, so no request value
// ever becomes a file path.

import { randomUUID } from 'node:crypto';
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { isAbsolute, join } from 'node:path';

const STORAGE_KEY = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;

export function newStorageKey() {
  return randomUUID();
}

export function assertStorageKey(key) {
  if (typeof key !== 'string' || !STORAGE_KEY.test(key)) {
    throw new Error('A media storage key must be a server-generated UUID.');
  }
  return key;
}

export class LocalDiskChatMediaStore {
  constructor({ root }) {
    if (typeof root !== 'string' || !isAbsolute(root)) {
      throw new Error('The media directory must be an absolute path.');
    }
    this.root = root;
    this.kind = 'local_disk';
  }

  #path(key) {
    return join(this.root, assertStorageKey(key));
  }

  async put(key, bytes) {
    await mkdir(this.root, { recursive: true, mode: 0o700 });
    // `wx` refuses to overwrite: a key is written once, and the bytes behind it never change.
    await writeFile(this.#path(key), bytes, { flag: 'wx', mode: 0o600 });
  }

  /** The stored bytes, or null when the object is gone. */
  async get(key) {
    try {
      return await readFile(this.#path(key));
    } catch (error) {
      if (error?.code === 'ENOENT') return null;
      throw error;
    }
  }

  /** Removing an absent object is success: deletion is idempotent. */
  async delete(key) {
    await rm(this.#path(key), { force: true });
  }
}
